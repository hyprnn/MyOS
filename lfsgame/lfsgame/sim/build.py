def kernel_headers_tree(user: str, group: str) -> dict:
    """usr/include as produced by 'make headers' (with the junk files LFS deletes)."""
    inc = mkdir_node(0o755, user, group)
    for d, files in HEADER_DIRS.items():
        sub = mkdir_node(0o755, user, group)
        for f in files:
            sub["c"][f] = file_node(f"/* {d}/{f}: Linux 6.10.5 UAPI header */\n", 0o644, user, group)
        sub["c"][".install"] = file_node("", 0o644, user, group)
        sub["c"]["..install.cmd"] = file_node("cmd_... := install headers\n", 0o644, user, group)
        inc["c"][d] = sub
    inc["c"]["Makefile"] = file_node("# usr/include/Makefile\n", 0o644, user, group)
    return inc
