"""Simulated package builds (LFS chapter 5): source trees, configure checks, make, install.

Nothing is compiled. A source tree is a small skeleton with the files the book's commands
touch. configure records its options in the build directory node (key "build"); make
"compiles" for a time based on the package's SBU value, may fail for the same reasons a
real build would (wrong options, missing previous steps), and install creates the files the
real package would install (only the ones the game checks), owned by the current user.

Pure logic: functions take the Machine and return output lines / raise BuildError.
"""
