class BuildError(Exception):
    """A failing configure/make step. lines: output to show before the error."""

    def __init__(self, message: str, lines: Optional[List[str]] = None, hint: str = ""):
        super().__init__(message)
        self.lines = lines or []
        self.hint = hint


# ---------------------------------------------------------------- source trees
def _f(data="", mode=0o644, **extra):
    node = file_node(data, mode)
    node.update(extra)
    return node


def _d(children: Dict[str, dict]):
    node = mkdir_node()
    node["c"] = children
    return node


LIMITX = "/* limitx.h */\n#ifndef _GCC_LIMITS_H_  /* LIMITX: start of the full limits.h */\n" \
         "#define _GCC_LIMITS_H_\n#ifndef _LIBC_LIMITS_H_\n#include \"syslimits.h\"\n#endif\n"
GLIMITS = "/* glimits.h: GLIMITS */\n#ifndef _LIMITS_H___\n#define _LIMITS_H___\n" \
          "#define CHAR_BIT __CHAR_BIT__\n#define INT_MAX __INT_MAX__\n#endif /* _LIMITS_H___ */\n"
LIMITY = "/* limity.h: LIMITY */\n#else /* not _GCC_LIMITS_H_ */\n#include_next <limits.h>\n" \
         "#endif /* not _GCC_LIMITS_H_ */\n"
T_LINUX64 = "# gcc/config/i386/t-linux64\nMULTILIB_OPTIONS    = m64/m32\n" \
            "MULTILIB_DIRNAMES   = 64 32\n" \
            "MULTILIB_OSDIRNAMES = m64=../lib64$(call if_multiarch,:x86_64-linux-gnu)\n" \
            "MULTILIB_OSDIRNAMES+= m32=$(if $(wildcard $(shell echo $(SYSTEM_HEADER_DIR))/../../usr/lib32),../lib32,../lib)\n"


def _configure(component: str):
    return _f("#! /bin/sh\n# Generated by GNU Autoconf (simulated)\n", 0o755,
              prog="configure", component=component)


def _guess():
    return _f("#! /bin/sh\n# config.guess (simulated)\n", 0o755, prog="config.guess")


def source_tree(file: str) -> Tuple[str, dict]:
    """(top directory name, node) for a package tarball name."""
    top = re.sub(r"\.tar\.(xz|gz|bz2)$", "", file)
    name = packages.BY_FILE[file].name
    common = {"README": _f(f"This is {top} (simulated source tree).\n"),
              "COPYING": _f("GNU GENERAL PUBLIC LICENSE (text not simulated)\n"),
              "ChangeLog": _f("(change log not simulated)\n")}
    c: Dict[str, dict] = dict(common)
    if name == "linux":
        c.pop("ChangeLog")
        c.update({"Makefile": _f("# SPDX-License-Identifier: GPL-2.0\nVERSION = 6\n", prog="kbuild"),
                  "arch": _d({"x86": _d({})}), "include": _d({"linux": _d({})}),
                  "kernel": _d({}), "scripts": _d({}), "usr": _d({"Makefile": _f("")}),
                  "Documentation": _d({})})
    else:
        c.update({"configure": _configure(name), "Makefile.in": _f("# Makefile.in\n"),
                  "INSTALL": _f("See the LFS book.\n")})
        if name == "binutils":
            for d in ("bfd", "binutils", "gas", "gprofng", "ld", "libiberty", "opcodes"):
                c[d] = _d({})
            c["config.guess"] = _guess()
        elif name == "gcc":
            c["gcc"] = _d({"limitx.h": _f(LIMITX), "glimits.h": _f(GLIMITS),
                           "limity.h": _f(LIMITY),
                           "config": _d({"i386": _d({"t-linux64": _f(T_LINUX64)})})})
            c["libstdc++-v3"] = _d({"configure": _configure("libstdc++"),
                                    "include": _d({}), "src": _d({})})
            for d in ("libgcc", "libgomp", "libcpp", "contrib"):
                c[d] = _d({})
            c["config.guess"] = _guess()
        elif name == "glibc":
            c["scripts"] = _d({"config.guess": _guess()})
            for d in ("elf", "nss", "nscd", "stdio-common", "sysdeps", "sunrpc"):
                c[d] = _d({})
            c["Makeconfig"] = _f("# Makeconfig\nvardbdir = $(localstatedir)/db\n")
        else:
            c["src"] = _d({})
    tree = _d(c)
    tree["srcpkg"] = name
    return top, tree


# ---------------------------------------------------------------- helpers
def parse_opts(args: List[str]) -> Tuple[Dict[str, str], List[str]]:
    """configure arguments -> ({"--prefix": "/x", "--disable-nls": ""}, [VAR=value...])."""
    opts, assigns = {}, []
    for a in args:
        if a.startswith("--"):
            k, eq, v = a.partition("=")
            opts[k] = v if eq else ""
        elif "=" in a:
            assigns.append(a)
            k, _, v = a.partition("=")
            opts[k] = v
    return opts, assigns


def find_tool(m, name: str, extra_dirs=()) -> Optional[str]:
    """Absolute path of an executable named ``name`` in extra_dirs or $PATH."""
    for d in list(extra_dirs) + m.env.get("PATH", "").split(":"):
        if not d:
            continue
        path = d.rstrip("/") + "/" + name
        try:
            node = m.resolve(path).node
        except FsError:
            continue
        if node is not None and node["t"] == "f" and node["m"] & 0o111:
            return path
    return None


def src_top(m, path: str) -> Tuple[Optional[str], Optional[dict]]:
    """Find the top of the source tree (node with 'srcpkg') that contains path."""
    p = m.resolve(path).path
    while True:
        node = m.resolve(p).node
        if node is not None and node.get("srcpkg"):
            return p, node
        if p == "/":
            return None, None
        p = p.rsplit("/", 1)[0] or "/"


def jobs(m, make_args: List[str]) -> int:
    n = 1
    for a in m.env.get("MAKEFLAGS", "").split() + list(make_args):
        mo = re.fullmatch(r"-j(\d*)", a) or re.fullmatch(r"--jobs=?(\d*)", a)
        if mo:
            n = int(mo.group(1)) if mo.group(1) else 8
    return max(1, n)


def speedup(n: int) -> float:
    return min(n, 8) ** 0.75


def checking(lines: List[str], *pairs):
    for what, result in pairs:
        lines.append(f"checking {what}... {result}")


def _compiler_env_check(m, lines: List[str]):
    cc = m.env.get("CC", "")
    if "distcc" in cc:
        checking(lines, ("for gcc", cc), ("whether the C compiler works", "no"))
        raise BuildError("C compiler cannot create executables\nSee `config.log' for more details",
                         lines, hint="CC is set to 'distcc gcc' in your environment (echo $CC). "
                                     "Where did it come from? See book 4.4.")


def _target_check(lines, opts, key="--target"):
    t = opts.get(key)
    if t is None:
        return None
    if t == "":
        raise BuildError(f"missing argument to {key}", lines,
                         hint="the variable used for it is empty - is LFS_TGT set? (book 4.4)")
    if t != TARGET:
        raise BuildError(f"/bin/sh ../config.sub {t} failed", lines,
                         hint=f"this game expects the target {TARGET} ($LFS_TGT)")
    return t


# ---------------------------------------------------------------- configure
def configure(m, component: str, srcdir: str, builddir: str, args: List[str]) -> Tuple[List[str], dict]:
    """Validate a configure run. Returns (output lines, build meta) or raises BuildError."""
    opts, _ = parse_opts(args)
    lines: List[str] = []
    in_tree = m.resolve(srcdir).path == m.resolve(builddir).path
    checking(lines, ("build system type", HOST_TRIPLET), ("host system type",
             opts.get("--host") or HOST_TRIPLET))
    if component not in CH5:
        raise BuildError(f"{component} is built in a later chapter of LFS", lines,
                         hint="the simulation only builds the chapter 5 packages so far")
    lfs = m.env.get("LFS", "")
    meta = {"component": component, "opts": opts, "srcdir": m.resolve(srcdir).path,
            "state": "configured"}

    if component == "binutils":
        t = _target_check(lines, opts)
        checking(lines, ("target system type", t or HOST_TRIPLET))
        _compiler_env_check(m, lines)
        checking(lines, ("for a BSD-compatible install", "/usr/bin/install -c"),
                 ("whether build environment is sane", "yes"),
                 ("for sysroot", opts.get("--with-sysroot", "no")))
    elif component == "gcc":
        if in_tree:
            raise BuildError("building GCC inside its source directory is not supported",
                             lines, hint="mkdir -v build; cd build; ../configure ...")
        t = _target_check(lines, opts)
        checking(lines, ("target system type", t or HOST_TRIPLET))
        _compiler_env_check(m, lines)
        src = m.lookup(srcdir)["c"]
        missing = [d for d in ("gmp", "mpfr", "mpc") if d not in src]
        checking(lines, ("for the correct version of gmp.h", "no" if "gmp" in missing else "buildlib"))
        if missing:
            raise BuildError("Building GCC requires GMP 4.2+, MPFR 3.1.0+ and MPC 0.8.0+.\n"
                             "Try the --with-gmp, --with-mpfr and/or --with-mpc options to specify\n"
                             "their locations.", lines,
                             hint=f"unpack {', '.join(missing)} into the GCC source tree "
                                  f"(tar -xf ../mpfr-*.tar.xz; mv -v mpfr-4.2.1 mpfr ...)")
        if t:
            prefix = opts.get("--prefix", "/usr/local")
            asm = find_tool(m, f"{t}-as", [prefix + "/bin"])
            checking(lines, (f"for {t}-as", asm or "no"))
            if asm is None:
                raise BuildError(f"cannot find an assembler for {t}", lines,
                                 hint="build Binutils pass 1 first, with the same --prefix "
                                      "($LFS/tools), and check PATH")
        checking(lines, ("for --enable-languages", opts.get("--enable-languages", "default")))
    elif component == "glibc":
        if in_tree:
            raise BuildError("you must configure in a separate build directory", lines)
        host = _target_check(lines, opts, "--host")
        if host is None:
            raise BuildError("this would build a glibc for the HOST, not for LFS", lines,
                             hint="glibc must be cross compiled: --host=$LFS_TGT")
        _compiler_env_check(m, lines)
        gcc = find_tool(m, f"{host}-gcc")
        checking(lines, (f"for {host}-gcc", gcc or "no"))
        if gcc is None:
            raise BuildError("C compiler cannot create executables\nSee `config.log' for more "
                             "details", lines, hint=f"{host}-gcc not found in PATH: is "
                                                    f"$LFS/tools/bin in PATH and GCC pass 1 installed?")
        headers = opts.get("--with-headers", f"{lfs}/usr/include")
        ok = m.exists(f"{headers}/linux/version.h")
        checking(lines, ("installed Linux kernel header files",
                         "6.10.5" if ok else "missing or too old!"))
        if not ok:
            raise BuildError("GNU libc requires kernel header files from\nLinux 3.2.0 or later "
                             "to be installed before configuring.", lines,
                             hint="install the Linux API headers first (book 5.4) and check "
                                  "--with-headers")
        meta["configparms"] = m.exists(builddir.rstrip("/") + "/configparms")
        top, topnode = src_top(m, srcdir)
        meta["patched"] = "fhs" in (topnode or {}).get("patches", [])
        checking(lines, ("for kernel header at least 4.19", "ok"),
                 ("for -fstack-protector", "yes"))
    elif component == "libstdc++":
        host = _target_check(lines, opts, "--host")
        if host is None:
            raise BuildError("this would build libstdc++ for the host", lines,
                             hint="use --host=$LFS_TGT")
        _compiler_env_check(m, lines)
        gcc = find_tool(m, f"{host}-gcc")
        checking(lines, (f"for {host}-gcc", gcc or "no"))
        if gcc is None:
            raise BuildError("C compiler cannot create executables", lines,
                             hint="the cross compiler from GCC pass 1 must be in PATH")
        if not m.exists(f"{lfs or '/mnt/lfs'}/usr/lib/libc.so.6"):
            checking(lines, ("for shl_load", ""))
            raise BuildError("Link tests are not allowed after GCC_NO_EXECUTABLES.", lines,
                             hint="glibc must be installed in $LFS first (book 5.5)")
        checking(lines, ("for g++ include dir", opts.get("--with-gxx-include-dir", "default")))
    lines.append("configure: creating ./config.status")
    lines.append("config.status: creating Makefile")
    return lines, meta


