def _bin(tool: str, **meta):
    node = file_node("", 0o755)
    node.update(prog=meta.pop("prog", "binutils"), tool=tool, **meta)
    node["size"] = 2_400_000
    return node


def _lib(size: int):
    return file_node(size=size)


def _ch6_files(m, meta, D, P, make_vars) -> List[Tuple[str, dict]]:
    c, o = meta["component"], meta["opts"]
    cross = not meta.get("native")
    out: List[Tuple[str, dict]] = []
    skip = set()
    if c == "coreutils":
        skip |= set(o.get("--enable-no-install-program", "").split(","))
        if "hostname" not in o.get("--enable-install-program", "").split(","):
            skip.add("hostname")
    for name in CH6_BINS[c]:
        if "->" in name:
            name, target = name.split("->")
            out.append((f"{D}{P}/bin/{name}", link_node(target)))
        elif name not in skip:
            out.append((f"{D}{P}/bin/{name}", _bin(name, prog="binary", cross=cross,
                                                   target=TARGET if cross else HOST_TRIPLET)))
    lib = f"{D}{P}/lib"
    if c == "ncurses":
        if not _native_tool(m, make_vars.get("TIC_PATH"), "tic"):
            raise BuildError("make[1]: *** [Makefile:115: install.data] Error 127",
                             ["../misc/run_tic.sh: line 135: tic: error while loading shared "
                              "libraries: libncursesw.so.6: cannot open shared object file",
                              "? tic could not build the terminfo database"],
                             hint="the cross-built tic cannot run on the host: build a native tic "
                                  "in build/ and pass TIC_PATH=$(pwd)/build/progs/tic")
        for name in ("ncursesw", "formw", "menuw", "panelw"):
            out += [(f"{lib}/lib{name}.so.6.5", _lib(450_000)),
                    (f"{lib}/lib{name}.so.6", link_node(f"lib{name}.so.6.5")),
                    (f"{lib}/lib{name}.so", link_node(f"lib{name}.so.6"))]
        curses = (f"/* curses.h for ncurses 6.5 */\n{CURSES_XOPEN}\n"
                  "#define NCURSES_WIDECHAR 1\n#endif\n")
        out += [(f"{D}{P}/include/curses.h", file_node(curses)),
                (f"{D}{P}/include/ncurses.h", link_node("curses.h")),
                (f"{D}{P}/share/terminfo/x/xterm", file_node(size=3_800)),
                (f"{D}{P}/share/terminfo/l/linux", file_node(size=1_800))]
    elif c == "coreutils":
        for page in ("ls.1", "cat.1", "chroot.1"):
            out.append((f"{D}{P}/share/man/man1/{page}",
                        file_node(f'.TH {page[:-2].upper()} "1" "August 2024" "GNU coreutils 9.5" '
                                  f'"User Commands"\n')))
    elif c == "file":
        out += [(f"{lib}/libmagic.so.1.0.0", _lib(180_000)),
                (f"{lib}/libmagic.so.1", link_node("libmagic.so.1.0.0")),
                (f"{lib}/libmagic.so", link_node("libmagic.so.1.0.0")),
                (f"{lib}/libmagic.la", file_node("# libmagic.la - a libtool library file\n")),
                (f"{D}{P}/share/misc/magic.mgc", file_node(size=7_600_000))]
    elif c == "findutils":
        var = o.get("--localstatedir", f"{P}/var")
        out.append((f"{D}{var}/README", file_node("locate database directory\n")))
    elif c == "gawk":
        top, topnode = src_top(m, meta["srcdir"])
        if "extras" in topnode["c"].get("Makefile.in", {}).get("data", ""):
            out.append((f"{lib}/gawk/filefuncs.so", _lib(30_000)))
    elif c == "xz":
        out += [(f"{lib}/liblzma.so.5.6.2", _lib(210_000)),
                (f"{lib}/liblzma.so.5", link_node("liblzma.so.5.6.2")),
                (f"{lib}/liblzma.so", link_node("liblzma.so.5.6.2")),
                (f"{lib}/liblzma.la", file_node("# liblzma.la - a libtool library file\n")),
                (f"{D}{o.get('--docdir', P + '/share/doc/xz')}/README", file_node("XZ Utils\n"))]
    return out


def install_files(m, meta: dict, destdir: str,
                  make_vars: Optional[Dict[str, str]] = None) -> List[Tuple[str, dict]]:
    """List of (absolute path, node) the install step creates. May raise BuildError."""
    c, o = meta["component"], meta["opts"]
    out: List[Tuple[str, dict]] = []
    D = destdir.rstrip("/")
    if c in CH6:
        return _ch6_files(m, meta, D, o.get("--prefix", "/usr/local").rstrip("/"),
                          make_vars or {})
    if meta.get("pass") == 2:
        P = o.get("--prefix", "/usr/local").rstrip("/")
        t = o.get("--target") or o["--host"]
        lib = f"{D}{P}/lib"
        if c == "binutils":
            for tool in ("addr2line", "ar", "as", "c++filt", "elfedit", "gprof", "ld", "ld.bfd",
                         "nm", "objcopy", "objdump", "ranlib", "readelf", "size", "strings",
                         "strip"):
                out.append((f"{D}{P}/bin/{tool}", _bin(tool, prog="binary", cross=True,
                                                       target=t)))
            for name in ("bfd", "ctf", "ctf-nobfd", "opcodes", "sframe"):
                out += [(f"{lib}/lib{name}.so", _lib(1_500_000)),
                        (f"{lib}/lib{name}.a", _lib(2_500_000)),
                        (f"{lib}/lib{name}.la", file_node(f"# lib{name}.la - libtool file\n"))]
        else:
            for tool in ("gcc", "g++", "cpp", "c++", f"{t}-gcc", f"{t}-g++", "gcc-ar", "gcov"):
                out.append((f"{D}{P}/bin/{tool}", _bin(tool, prog="binary", cross=True,
                                                       target=t)))
            gl = f"{lib}/gcc/{t}/{GCC_VER}"
            out += [(f"{gl}/libgcc.a", _lib(5_200_000)), (f"{gl}/crtbegin.o", _lib(3_000)),
                    (f"{gl}/include/stddef.h", file_node("/* stddef.h */\n")),
                    (f"{D}{P}/libexec/gcc/{t}/{GCC_VER}/cc1", _bin("cc1", prog="binary",
                                                                     cross=True, target=t)),
                    (f"{lib}/libgcc_s.so.1", _lib(150_000)),
                    (f"{lib}/libstdc++.so.6.0.33", _lib(21_000_000))]
        return out
    if c == "binutils":
        P = o.get("--prefix", "/usr/local").rstrip("/")
        t = o.get("--target")
        pre = f"{t}-" if t else ""
        info = dict(target=t or HOST_TRIPLET, sysroot=o.get("--with-sysroot", "/"))
        for tool in ("addr2line", "ar", "as", "c++filt", "elfedit", "gprof", "ld", "ld.bfd",
                     "nm", "objcopy", "objdump", "ranlib", "readelf", "size", "strings", "strip"):
            out.append((f"{D}{P}/bin/{pre}{tool}", _bin(tool, **info)))
        if t:
            for tool in ("ar", "as", "ld", "ld.bfd", "nm", "objcopy", "objdump", "ranlib",
                         "readelf", "strip"):
                out.append((f"{D}{P}/{t}/bin/{tool}", _bin(tool, **info)))
            out.append((f"{D}{P}/{t}/lib/ldscripts/elf_x86_64.x", file_node("/* ld script */\n")))
    elif c == "gcc":
        P = o.get("--prefix", "/usr/local").rstrip("/")
        t = o.get("--target") or HOST_TRIPLET
        info = dict(prog="gcc", target=t, sysroot=o.get("--with-sysroot", "/"), prefix=P,
                    pass1="--with-newlib" in o)
        for tool in ("gcc", "g++", "cpp", "c++", f"gcc-{GCC_VER}", "gcc-ar", "gcc-nm",
                     "gcc-ranlib", "gcov"):
            out.append((f"{D}{P}/bin/{t}-{tool}", _bin(tool, **info)))
        lib = f"{D}{P}/lib/gcc/{t}/{GCC_VER}"
        out += [(f"{lib}/libgcc.a", file_node(size=5_100_000)),
                (f"{lib}/crtbegin.o", file_node(size=3_000)),
                (f"{lib}/crtend.o", file_node(size=1_200)),
                (f"{lib}/include/stddef.h", file_node("/* stddef.h from GCC */\n")),
                (f"{lib}/include/stdarg.h", file_node("/* stdarg.h from GCC */\n")),
                (f"{lib}/include/limits.h",
                 file_node("/* limits.h installed by GCC pass 1: INCOMPLETE (it does not\n"
                           "   include the system limits.h). See LFS 5.3. */\n")),
                (f"{lib}/install-tools/mkheaders.conf", file_node("")),
                (f"{D}{P}/libexec/gcc/{t}/{GCC_VER}/cc1", _bin("cc1", prog="binary")),
                (f"{D}{P}/libexec/gcc/{t}/{GCC_VER}/collect2", _bin("collect2", prog="binary"))]
    elif c == "glibc":
        P = o.get("--prefix", "/usr/local").rstrip("/")
        sbindir = f"{P}/sbin" if meta.get("configparms") else "/sbin"
        lib = f"{D}{P}/lib"
        ldd = ("#!/bin/bash\n# ldd: print shared object dependencies (simulated)\n"
               f"RTLDLIST=\"{P}/lib/ld-linux.so.2 {P}/lib64/ld-linux-x86-64.so.2 "
               f"{P}/libx32/ld-linux-x32.so.2\"\necho \"ldd is simulated\"\n")
        out += [(f"{lib}/libc.so.6", file_node(size=2_150_000)),
                (f"{lib}/libc.so", file_node(f"/* GNU ld script */\nGROUP ( {P}/lib/libc.so.6 "
                                             f"{P}/lib/libc_nonshared.a AS_NEEDED ( "
                                             f"{P}/lib/ld-linux-x86-64.so.2 ) )\n")),
                (f"{lib}/libc_nonshared.a", file_node(size=22_000)),
                (f"{lib}/libm.so.6", file_node(size=950_000)),
                (f"{lib}/ld-linux-x86-64.so.2", file_node(size=230_000)),
                (f"{lib}/crt1.o", file_node(size=4_000)),
                (f"{lib}/Scrt1.o", file_node(size=4_000)),
                (f"{lib}/crti.o", file_node(size=1_500)),
                (f"{lib}/crtn.o", file_node(size=1_300)),
                (f"{D}{P}/include/stdio.h", file_node("/* stdio.h from glibc 2.40 */\n")),
                (f"{D}{P}/include/stdlib.h", file_node("/* stdlib.h from glibc 2.40 */\n")),
                (f"{D}{P}/include/unistd.h", file_node("/* unistd.h from glibc 2.40 */\n")),
                (f"{D}{P}/include/limits.h", file_node("/* limits.h from glibc 2.40 */\n")),
                (f"{D}{P}/include/gnu/stubs.h", file_node("/* gnu/stubs.h */\n")),
                (f"{D}{P}/bin/ldd", file_node(ldd, 0o755)),
                (f"{D}{P}/bin/getconf", _bin("getconf", prog="binary")),
                (f"{D}{sbindir}/ldconfig", _bin("ldconfig", prog="binary")),
                (f"{D}{sbindir}/sln", _bin("sln", prog="binary"))]
        if meta.get("patched"):
            out.append((f"{D}/var/lib/nss_db/Makefile", file_node("# nss_db (FHS location)\n")))
        else:
            out.append((f"{D}/var/db/Makefile", file_node("# nss_db (NOT FHS compliant)\n")))
    elif c == "libstdc++":
        P = o.get("--prefix", "/usr/local").rstrip("/")
        inc = o.get("--with-gxx-include-dir", f"{P}/include/c++/{GCC_VER}").rstrip("/")
        lib = f"{D}{P}/lib"
        for name, size in (("libstdc++.so.6.0.33", 21_000_000), ("libstdc++.a", 6_600_000),
                           ("libstdc++exp.a", 300_000), ("libstdc++fs.a", 1_200_000),
                           ("libsupc++.a", 900_000)):
            out.append((f"{lib}/{name}", file_node(size=size)))
        for la in ("libstdc++.la", "libstdc++exp.la", "libstdc++fs.la", "libsupc++.la"):
            out.append((f"{lib}/{la}", file_node(f"# {la} - a libtool library file\n"
                                                 f"libdir='{P}/lib'\n")))
        out.append((f"{lib}/libstdc++.so.6", link_node("libstdc++.so.6.0.33")))
        out.append((f"{lib}/libstdc++.so", link_node("libstdc++.so.6.0.33")))
        for h in ("iostream", "string", "vector", "bits/c++config.h"):
            out.append((f"{D}{inc}/{h}", file_node(f"// <{h}> from libstdc++ {GCC_VER}\n")))
    return out


